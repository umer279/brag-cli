import fs from 'node:fs';
import path from 'node:path';
import { dataDir } from './store.ts';
import { groupByMonthWeek, countBy, shortDate, dateRange } from './group.ts';
import type { Entry } from './types.ts';

export interface RenderOptions {
  title?: string;
  export?: boolean;
}

/**
 * journal.md (default) or an export (`export: true`): the export takes a custom title,
 * describes an empty range instead of the whole journal, and ends with a Highlights section.
 */
export function renderMarkdown(entries: Entry[], { title = 'Brag Journal', export: isExport = false }: RenderOptions = {}): string {
  const lines = [`# ${title}`, ''];
  const range = dateRange(entries);
  if (!range) {
    lines.push(isExport ? '_No entries in this range._' : '_No entries yet. Add one with `brag add "..."`._', '');
    return lines.join('\n');
  }
  const projects = new Set(entries.map((e) => e.project).filter(Boolean));
  const summary = [
    `${entries.length} ${entries.length === 1 ? 'win' : 'wins'}`,
    isExport && projects.size ? `${projects.size} ${projects.size === 1 ? 'project' : 'projects'}` : null,
    `${shortDate(range.from)} ${range.from.slice(0, 4)} – ${shortDate(range.to)} ${range.to.slice(0, 4)}`,
  ].filter(Boolean);
  lines.push(`_${summary.join(' · ')}_`, '');
  if (!isExport) lines.push('<!-- Auto-generated by brag. Edit entries with `brag edit`, not here. -->', '');
  for (const month of groupByMonthWeek(entries)) {
    lines.push(`## ${month.label}`, '');
    for (const week of month.weeks) {
      lines.push(`### ${week.label}`, '');
      for (const e of week.entries) {
        lines.push(`- **${e.text}** _(${shortDate(e.date)})_`);
        if (e.impact) lines.push(`  - Impact: ${e.impact}`);
        const meta = [e.project && `Project: ${e.project}`, e.tags.length && e.tags.map((t) => `#${t}`).join(' ')].filter(Boolean);
        if (meta.length) lines.push(`  - ${meta.join(' · ')}`);
        for (const link of e.links) lines.push(`  - <${link}>`);
      }
      lines.push('');
    }
  }
  if (isExport) lines.push(...highlights(entries));
  return lines.join('\n');
}

function highlights(entries: Entry[]): string[] {
  const sections: [string, [string, number][], string][] = [
    ['By project', countBy(entries, (e) => e.project), ''],
    ['By tag', countBy(entries, (e) => e.tags), '#'],
  ];
  const nonEmpty = sections.filter(([, counts]) => counts.length);
  if (!nonEmpty.length) return [];
  const lines = ['## Highlights', ''];
  for (const [heading, counts, prefix] of nonEmpty) {
    lines.push(`### ${heading}`, '', ...counts.map(([name, n]) => `- **${prefix}${name}** — ${n}`), '');
  }
  return lines;
}

export function writeMarkdown(entries: Entry[], file = path.join(dataDir(), 'journal.md')): string {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, renderMarkdown(entries), 'utf8');
  return file;
}

export function exportMarkdown(entries: Entry[], file: string, { title }: { title?: string } = {}): string {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, renderMarkdown(entries, { title, export: true }), 'utf8');
  return file;
}
